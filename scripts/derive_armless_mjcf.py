#!/usr/bin/env python3
"""Derive the armless 14-DoF MJCF (ticket #3) from the 19-DoF with-arms robot.xml.

Reads  microduck/src/model/mjcf/robot.xml  (19 servos: 12 leg + 6 arm + 1 head)
Writes microduck/src/model/mjcf/robot_armless_14.xml

Derivation rules (see docs/adr/0006-armless-14dof-mjcf.md):
1. Arm subtrees (shoulder/humerus/radius, 3 DoF x 2) are deleted as whole
   <body> blocks — never mass-zeroed — so the mass distribution matches the
   real armless build (no arm servos, no arm prints).
2. ankle_roll joints (right/left) are removed; the foot bodies stay as welded
   children so their mass merges into the ankle link. The 14-servo build has
   no servo at ankle roll and the constants table has no such motor.
3. The single `head` hinge is replaced by 4 co-located hinges named exactly as
   the constants motors: head_pitch, head_roll, head_yaw, neck_pitch
   (IDs 11/14/13/12). Axes chosen so local axes map to world pitch/roll/yaw
   given the head body's Rz(+90 deg) frame.
4. Actuators are exactly the 14 constants motor names (MJCF names), BAM-driven
   by the aligned launcher.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "microduck/src/model/mjcf/robot.xml"
DST = ROOT / "microduck/src/model/mjcf/robot_armless_14.xml"

text = SRC.read_text(encoding="utf-8")

# --- 1. delete whole arm subtrees (between their header comment and the next link) ---
def cut_block(text: str, start_marker: str, end_marker: str) -> str:
    i = text.index(start_marker)
    j = text.index(end_marker)
    assert i < j, (start_marker, end_marker)
    return text[:i] + text[j:]

text = cut_block(text, "      <!-- Link shoulder -->", "      <!-- Link hip -->")
text = cut_block(text, "      <!-- Link shoulder_2 -->", "      <!-- Link hip_2 -->")

# --- 2. weld the ankle_roll joints (foot becomes a fixed child of the ankle link) ---
n_before = text.count("\n")
for name in ("right_ankle_roll", "left_ankle_roll"):
    pat = re.compile(rf'^[ \t]*<joint axis="0 0 1" name="{name}"[^\n]*\n', re.M)
    text, n = pat.subn("", text)
    assert n == 1, (name, n)

# --- 3. head: one hinge -> 4 co-located hinges named after constants IDs 11-14 ---
m = re.search(r'^[ \t]*<joint axis="0 0 1" name="head" .*\n', text, re.M)
assert m, "head joint line not found"
old_head = m.group(0)
new_head = """        <!-- 14-DoF head/neck: 4 co-located hinges, names = constants IDs 11-14.
             Head body frame is Rz(+90 deg): local +x -> world pitch (+y),
             local -y -> world roll (+x), local z -> world yaw (z). -->
        <joint axis="1 0 0" name="head_pitch" type="hinge" range="-0.6 0.6" class="xl330"/>
        <joint axis="0 -1 0" name="head_roll" type="hinge" range="-0.6 0.6" class="xl330"/>
        <joint axis="0 0 1" name="head_yaw" type="hinge" range="-1.5707963267948966 1.5707963267948966" class="xl330"/>
        <joint axis="1 0 0" name="neck_pitch" type="hinge" range="-0.6 0.6" class="xl330"/>
"""
text = text.replace(old_head, new_head)

# --- 4. actuator block: exactly the 14 constants motors ---
ACTUATORS = [
    "right_hip_yaw", "right_hip_roll", "right_hip_pitch", "right_knee", "right_ankle_pitch",
    "left_hip_yaw", "left_hip_roll", "left_hip_pitch", "left_knee", "left_ankle_pitch",
    "neck_pitch", "head_pitch", "head_yaw", "head_roll",
]
act_block = "  <actuator>\n" + "".join(
    f'    <motor class="xl330" name="{n}" joint="{n}"/>\n' for n in ACTUATORS
) + "  </actuator>"
text = re.sub(r"  <actuator>.*?</actuator>", act_block, text, flags=re.S)

# --- 5. drop now-unused arm meshes/materials ---
for mesh in ("shoulder.stl", "humerus.stl", "radius.stl"):
    pat = re.compile(rf'^[ \t]*<mesh file="{re.escape(mesh)}"/>\n', re.M)
    text, n = pat.subn("", text)
    assert n == 1, (mesh, n)
for mat in ("shoulder_material", "humerus_material", "radius_material"):
    pat = re.compile(rf'^[ \t]*<material name="{mat}"[^\n]*\n', re.M)
    text, n = pat.subn("", text)
    assert n == 1, (mat, n)

# --- provenance header ---
text = text.replace(
    "<mujoco model=\"microduck\">",
    "<!-- Armless 14-DoF derivative of robot.xml (ticket #3, armless-hd1910).\n"
    "     Generated by scripts/derive_armless_mjcf.py — edit that script, not this file,\n"
    "     then re-run it. Arms deleted as whole bodies; ankle_roll welded;\n"
    "     head expanded to 4 hinges matching constants IDs 11-14. -->\n"
    "<mujoco model=\"microduck\">",
    1,
)

DST.write_text(text, encoding="utf-8", newline="\n")
print(f"wrote {DST} ({len(text.splitlines())} lines)")

scene_src = ROOT / "microduck/src/model/mjcf/scene.xml"
scene = scene_src.read_text(encoding="utf-8")
scene = scene.replace('<include file="robot.xml" />', '<include file="robot_armless_14.xml" />')
scene_dst = ROOT / "microduck/src/model/mjcf/scene_armless_14.xml"
scene_dst.write_text(scene, encoding="utf-8", newline="\n")
print(f"wrote {scene_dst}")
